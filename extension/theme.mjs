// The settings page's CSS custom properties, from design/theme.md's tables
// (plans/06-settings.md, Decision 8). build.mjs writes the result to
// src/options/theme.gen.css, committed like wire.gen.ts, and
// test/theme.test.ts checks the committed file is fresh.

const FALLBACK = {
  "font.text": 'system-ui, -apple-system, "Segoe UI", sans-serif',
  "font.mono": 'ui-monospace, "SF Mono", Menlo, monospace',
};

/** Rows of every table whose first two cells are `code`. */
function rows(markdown) {
  const out = [];
  for (const line of markdown.split("\n")) {
    const m = /^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|/.exec(line);
    if (m) out.push([m[1], m[2]]);
  }
  return out;
}

const cssName = (token) => `--${token.replace(/[./]/g, "-")}`;

/** The CSS for design/theme.md's text. */
export function themeCss(markdown) {
  const global = [];
  const light = [];
  const dark = [];
  for (const [token, value] of rows(markdown)) {
    const mode = /^(light|dark)\/(\w+)$/.exec(token);
    if (mode) {
      (mode[1] === "light" ? light : dark).push(`  ${cssName(`color.${mode[2]}`)}: ${value};`);
    } else if (FALLBACK[token]) {
      global.push(`  ${cssName(token)}: "${value}", ${FALLBACK[token]};`);
    } else {
      global.push(`  ${cssName(token)}: ${value};`);
    }
  }
  if (!global.length || !light.length || light.length !== dark.length) {
    throw new Error(`design/theme.md: expected global tokens and as many light as dark colours (got ${global.length}, ${light.length}, ${dark.length})`);
  }
  return [
    "/* Generated by extension/build.mjs from design/theme.md. Do not edit. */",
    ":root {",
    "  color-scheme: light dark;",
    ...global,
    ...light,
    "}",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    ...dark.map((l) => `  ${l}`),
    "  }",
    "}",
    "",
  ].join("\n");
}
