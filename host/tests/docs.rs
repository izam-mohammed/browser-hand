//! The reference pages of the docs book (plans/11-docs.md): `tools.md` and
//! `settings.md` are written from the host's own types, `commands.md` is
//! checked against `src/main.rs`. `UPDATE_DOCS=1 cargo test --test docs`
//! rewrites the generated pages; without it a stale page fails the test.

use std::fmt::Write as _;
use std::path::PathBuf;

use browser_hand::config::Settings;
use browser_hand::mcp::Server;
use rmcp::schemars::schema_for;
use serde_json::Value;

fn page(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../docs/book/src/reference")
        .join(name)
}

/// Writes `want` when `UPDATE_DOCS` is set, otherwise fails if the page differs.
fn settle(name: &str, want: String) {
    let path = page(name);
    if std::env::var_os("UPDATE_DOCS").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "docs/book/src/reference/{name} is stale: run `UPDATE_DOCS=1 cargo test --manifest-path host/Cargo.toml --test docs`"
    );
}

/// Follows a `$ref` into `$defs`.
fn resolve<'a>(root: &'a Value, schema: &'a Value) -> &'a Value {
    match schema.get("$ref").and_then(Value::as_str) {
        Some(r) => r
            .strip_prefix("#/")
            .and_then(|path| path.split('/').try_fold(root, |v, k| v.get(k)))
            .unwrap_or(schema),
        None => schema,
    }
}

/// A short type name: `string`, `integer`, `"a" | "b"`, `array of string`.
fn type_of(root: &Value, schema: &Value) -> String {
    let s = resolve(root, schema);
    if let Some(vs) = s.get("enum").and_then(Value::as_array) {
        return vs
            .iter()
            .map(|v| format!("`{v}`"))
            .collect::<Vec<_>>()
            .join(" or ");
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(parts) = s.get(key).and_then(Value::as_array) {
            let mut seen: Vec<String> = Vec::new();
            for p in parts {
                let t = type_of(root, p);
                if t != "null" && !seen.contains(&t) {
                    seen.push(t);
                }
            }
            return seen.join(" or ");
        }
    }
    match s.get("type") {
        Some(Value::String(t)) if t == "array" => match s.get("items") {
            Some(items) => format!("array of {}", type_of(root, items)),
            None => "array".into(),
        },
        Some(Value::String(t)) => t.clone(),
        Some(Value::Array(ts)) => ts
            .iter()
            .filter_map(Value::as_str)
            .filter(|t| *t != "null")
            .collect::<Vec<_>>()
            .join(" or "),
        _ => "any".into(),
    }
}

/// One line of text from a doc comment or description.
fn flat(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
        .replace('<', "&lt;")
}

fn tools_page() -> String {
    let mut tools = Server::tool_router().list_all();
    tools.sort_by(|a, b| a.name.cmp(&b.name));
    let mut out = String::new();
    out.push_str("# tools\n\n");
    out.push_str(
        "<!-- Generated by `UPDATE_DOCS=1 cargo test --manifest-path host/Cargo.toml --test docs`. Do not edit by hand. -->\n\n",
    );
    let _ = writeln!(
        out,
        "browser-hand gives Claude {} tools, listed here by name. Each entry is the \
         description the server sends to Claude, so it is also how Claude \
         reads the tool. Read-only tools never change a page.\n",
        tools.len()
    );
    for t in &tools {
        let _ = writeln!(out, "## `{}`\n", t.name);
        let ann = t.annotations.as_ref();
        let mut flags = Vec::new();
        if ann.and_then(|a| a.read_only_hint) == Some(true) {
            flags.push("read-only");
        }
        if ann.and_then(|a| a.destructive_hint) == Some(true) {
            flags.push("destructive");
        }
        if !flags.is_empty() {
            let _ = writeln!(out, "*{}*\n", flags.join(", "));
        }
        let _ = writeln!(
            out,
            "{}\n",
            t.description
                .as_deref()
                .unwrap_or("")
                .trim()
                .replace('<', "&lt;")
        );
        let schema = Value::Object((*t.input_schema).clone());
        let props = schema.get("properties").and_then(Value::as_object);
        match props {
            Some(props) if !props.is_empty() => {
                let required: Vec<&str> = schema
                    .get("required")
                    .and_then(Value::as_array)
                    .map(|r| r.iter().filter_map(Value::as_str).collect())
                    .unwrap_or_default();
                out.push_str(
                    "| Input | Type | Required | What it is |\n| --- | --- | --- | --- |\n",
                );
                for (name, p) in props {
                    let desc = resolve(&schema, p)
                        .get("description")
                        .or_else(|| p.get("description"))
                        .and_then(Value::as_str)
                        .unwrap_or("");
                    let _ = writeln!(
                        out,
                        "| `{name}` | {} | {} | {} |",
                        type_of(&schema, p),
                        if required.contains(&name.as_str()) {
                            "yes"
                        } else {
                            "no"
                        },
                        flat(desc)
                    );
                }
                out.push('\n');
            }
            _ => out.push_str("No inputs.\n\n"),
        }
    }
    out
}

/// What the settings page calls each key (`extension/src/options/page.ts`).
/// A key with no entry here fails the test, so a new setting gets a label.
const LABELS: &[(&str, &str)] = &[
    ("input.pace", "Pace"),
    ("input.typing_speed", "Typing speed"),
    ("input.mouse_speed", "Mouse speed"),
    ("sessions.default_profile", "Default profile"),
    ("sessions.new_window", "Open a new window"),
    (
        "sessions.close_tabs_on_end",
        "Close tabs when the session ends",
    ),
    ("sites.blocked", "Blocked sites"),
    ("sites.read_only", "Read-only sites"),
    ("capture.screenshot_size", "Screenshot size"),
    ("capture.screenshot_quality", "Screenshot quality"),
    ("capture.gif_folder", "GIF folder"),
    ("capture.gif_frame_delay_ms", "GIF frame delay"),
    ("debugger.detach_after_idle_s", "Detach after idle"),
];

fn settings_page() -> String {
    let schema = serde_json::to_value(schema_for!(Settings)).unwrap();
    let defaults = serde_json::to_value(Settings::default()).unwrap();
    let mut out = String::new();
    out.push_str("# settings\n\n");
    out.push_str(
        "<!-- Generated by `UPDATE_DOCS=1 cargo test --manifest-path host/Cargo.toml --test docs`. Do not edit by hand. -->\n\n",
    );
    out.push_str(
        "The settings page writes these keys to `~/.config/browser-hand/config.toml` \
         (`$XDG_CONFIG_HOME/browser-hand/config.toml` when set). A missing file or \
         key is the default, and an unknown key is dropped. The first column is the \
         key in the file; the second is what the settings page calls it.\n\n",
    );
    let mut seen = Vec::new();
    for (section, sref) in schema["properties"].as_object().unwrap() {
        let s = resolve(&schema, sref);
        let Some(props) = s.get("properties").and_then(Value::as_object) else {
            continue;
        };
        let _ = writeln!(out, "## `[{section}]`\n");
        out.push_str("| Key | Settings page | Type | Default | What it does |\n| --- | --- | --- | --- | --- |\n");
        for (key, p) in props {
            let path = format!("{section}.{key}");
            let label = LABELS
                .iter()
                .find(|(k, _)| *k == path)
                .unwrap_or_else(|| panic!("add `{path}` to LABELS in host/tests/docs.rs"))
                .1;
            seen.push(path.clone());
            let desc = resolve(&schema, p)
                .get("description")
                .or_else(|| p.get("description"))
                .and_then(Value::as_str)
                .unwrap_or("");
            let _ = writeln!(
                out,
                "| `{key}` | {label} | {} | `{}` | {} |",
                type_of(&schema, p),
                defaults[section][key],
                flat(desc)
            );
        }
        out.push('\n');
    }
    for (k, _) in LABELS {
        assert!(
            seen.iter().any(|s| s == k),
            "LABELS names `{k}`, which Settings no longer has"
        );
    }
    out.push_str(&format!(
        "The file's top-level `version` key is {}.\n",
        defaults["version"]
    ));
    out
}

#[test]
fn tools_page_matches_the_server() {
    settle("tools.md", tools_page());
}

#[test]
fn settings_page_matches_the_settings() {
    settle("settings.md", settings_page());
}

/// Every command `src/main.rs` matches on is named in `commands.md`.
#[test]
fn commands_page_names_every_command() {
    let main =
        std::fs::read_to_string(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/main.rs"))
            .unwrap();
    let doc =
        std::fs::read_to_string(page("commands.md")).expect("docs/book/src/reference/commands.md");
    let mut found = 0;
    for line in main.lines() {
        let line = line.trim();
        // A match arm on a string literal: `"mcp" => ...`.
        if let Some(rest) = line.strip_prefix('"') {
            if let Some((name, after)) = rest.split_once('"') {
                if after.trim_start().starts_with("=>") {
                    found += 1;
                    assert!(
                        doc.contains(&format!("`browser-hand {name}")),
                        "commands.md does not name the `{name}` command"
                    );
                }
            }
        }
    }
    assert!(
        found >= 4,
        "found only {found} commands in main.rs: did its match change shape?"
    );
    assert!(doc.contains("--uninstall"));
}
